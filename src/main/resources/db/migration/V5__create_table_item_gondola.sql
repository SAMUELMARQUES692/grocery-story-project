CREATE TABLE item_gondolas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gondola_id BIGINT NOT NULL REFERENCES gondolas(id),
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    prateleira INTEGER NOT NULL CHECK (prateleira >= 0),
    quantidade_atual INTEGER NOT NULL CHECK ( quantidade_atual >= 0 ),
    capacidade_maxima INTEGER NOT NULL CHECK ( capacidade_maxima >= 0 ),
    capacidade_minima INTEGER NOT NULL CHECK ( capacidade_minima >= 0 ),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP,
    CONSTRAINT uk_item_gondola_produto UNIQUE (gondola_id, produto_id),
    CONSTRAINT ck_item_gondola_limites CHECK (capacidade_minima <= capacidade_maxima
        AND quantidade_atual <= capacidade_maxima)
);

CREATE INDEX idx_item_gondolas_produto_id ON item_gondolas(produto_id);