CREATE TABLE produtos(
    id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_de_barras VARCHAR(14) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    preco_custo DECIMAL (10, 2) NOT NULL CHECK (preco_custo >= 0),
    preco_venda DECIMAL (10, 2) NOT NULL CHECK (preco_custo >= 0),
    unidade_medida VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT true,
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    fornecedor_id BIGINT NOT NULL REFERENCES fornecedores(id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP
);

CREATE INDEX idx_produtos_categoria_id ON produtos(categoria_id);
CREATE INDEX idx_produtos_fornecedor_id ON produtos(fornecedor_id);

