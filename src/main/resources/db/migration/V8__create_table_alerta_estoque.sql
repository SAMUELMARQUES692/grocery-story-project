CREATE TABLE alerta_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    local_produto VARCHAR(20) NOT NULL,
    quantidade_no_momento INTEGER NOT NULL,
    status_alerta VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
    email_enviado BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP
);

CREATE INDEX idx_alerta_estoque_produto_id ON alerta_estoque(produto_id);

CREATE UNIQUE INDEX uk_alerta_aberto_produto_local
    ON alerta_estoque (produto_id, local_produto)
    WHERE status_alerta = 'ABERTO';